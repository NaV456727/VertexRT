#include "vrt_timer.h"
#include "vrt_tick.h"

/*=========================================================
 * Timer Initialization
 *=========================================================*/

void vrt_timer_init(void)
{
    vrt_tick_init();
}

/*=========================================================
 * Timer Start
 *=========================================================*/

void vrt_timer_start(void)
{
    vrt_tick_start();
}

/*=========================================================
 * Timer Stop
 *=========================================================*/

void vrt_timer_stop(void)
{
    vrt_tick_stop();
}